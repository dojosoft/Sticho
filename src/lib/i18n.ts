/**
 * 生成翻译函数：locale 变化时由 $derived 重新生成，标记文本随之更新。
 *
 * 组件自身只知道 locale，拿不到语言包词表；由 App 把当前语种的合并词表（内置 + 语言包）
 * 作为 `entries` 注入后即优先使用它，避免切换自定义语言包时组件仍查内置固定表。
 */
export function makeT(locale: Locale, entries?: Record<string, string>) {
  if (entries) return makeTFrom(entries);
  return makeTFrom(locale === "zh-CN" ? ZH : {});
}

/**
 * 生成翻译函数：直接吃一份「键 → 译文」词表。
 *
 * 界面语言不再写死 zh-CN / en-US 两种，而是由 locales/ 目录下的语言包提供词表；
 * 这里只负责查表 + 插值，查不到就回落英文原文（与既有设计一致，增量补齐不会显示空白）。
 * 英文包（及其它未提供词表的语种）传入空对象，查表必然落空 → 原样返回英文键，正是期望行为。
 */
export function makeTFrom(entries: Record<string, string>) {
  return (key: string, vars?: Vars): string => {
    const raw = entries[key] ?? key;
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (whole, name: string) =>
      name in vars ? String(vars[name]) : whole,
    );
  };
}

/** 供查缺使用：已收录的中文词条数（不参与界面逻辑） */
export function zhEntryCount(): number {
  return Object.keys(ZH).length;
}

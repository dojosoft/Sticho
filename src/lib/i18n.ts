/**
 * 界面多语言
 *
 * 设计要点：**以英文原文为键**。
 * - `t("File")` 在 zh-CN 下查 ZH 词表返回「文件」；
 * - 其它语种在其语言包词表里查不到时回落英文原文——
 *   任何还没进词表的字符串都不会变成空白或 key，转换过程中可随时增量补齐。
 * - 需要插值的地方写占位符：`t("Save {n} files", { n: 3 })`。
 *
 * 用法（App.svelte）：
 * ```ts
 * let locale = $state<Locale>("en-US");
 * const t = $derived(makeT(locale));
 * ```
 * `LOCALES` 为设置面板里可选的语种清单。
 *
 * Vditor 自身的语言（`lang` 选项）用的是另一套命名（zh_CN / en_US），
 * 由 editor.ts 的 `setEditorLocale` 负责映射。
 */

export type Locale = string;

/** 内置语种（语言包缺失或未加载时的兜底清单） */
export const LOCALES: { id: Locale; label: string }[] = [
  { id: "zh-CN", label: "简体中文" },
  { id: "en-US", label: "English" },
];

export type Vars = Record<string, string | number>;

/**
 * 语言 id → Vditor 的 lang 选项值。
 *
 * Vditor 只自带 zh_CN / en_US 两套文案，按前缀粗判：zh 开头用中文，其余一律英文——
 * 与「软件默认语言为英文、未覆盖的字段回落英文」的整体设计一致。
 */
export function vditorLang(locale: Locale): "zh_CN" | "en_US" {
  return locale.toLowerCase().startsWith("zh") ? "zh_CN" : "en_US";
}

